// Scans DATA/<category>/<CODE - Course name>/NN-chapter.md and writes
// UI/courses.js, so the UI never hardcodes the course list.
// Run from the repo root: node scripts/build-course-catalog.js
const fs = require("fs");
const path = require("path");

const DATA_DIR = path.join(__dirname, "..", "DATA");
const OUT_FILE = path.join(__dirname, "..", "UI", "courses.js");

const CATEGORY_LABELS = {
  BUS: "Business",
  DAT: "Data",
  HUM: "Humanities",
  MAT: "Mathematics",
};

// First line of a chapter is "# 3. Internal rate of return" or "# Preface".
function readChapterTitle(file, fallback) {
  const firstLine = fs.readFileSync(file, "utf8").split("\n")[0];
  const title = firstLine.replace(/^#\s*/, "").replace(/^\d+\.\s*/, "").trim();
  return title || fallback;
}

function listDirs(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

const catalog = [];

for (const category of listDirs(DATA_DIR)) {
  const courses = [];

  for (const folder of listDirs(path.join(DATA_DIR, category))) {
    // Folder names look like "BUS33-3 - Corporate Finance".
    const match = folder.match(/^(\S+)\s+-\s+(.+)$/);
    if (!match) continue;

    const courseDir = path.join(DATA_DIR, category, folder);
    const chapters = fs
      .readdirSync(courseDir)
      .filter((name) => name.endsWith(".md"))
      .sort()
      .map((name) => {
        const id = name.replace(/\.md$/, "");
        return { id, title: readChapterTitle(path.join(courseDir, name), id) };
      });

    if (chapters.length > 0) {
      courses.push({ code: match[1], name: match[2], folder, chapters });
    }
  }

  // Skips empty placeholder folders (e.g. DATA/BUSINESS).
  if (courses.length > 0) {
    catalog.push({
      id: category,
      label: CATEGORY_LABELS[category] || category,
      courses,
    });
  }
}

const output =
  "// Generated by scripts/build-course-catalog.js. Do not edit by hand.\n" +
  `const CATALOG = ${JSON.stringify(catalog, null, 2)};\n`;

fs.writeFileSync(OUT_FILE, output);
console.log(
  `Wrote ${path.relative(process.cwd(), OUT_FILE)}: ` +
    `${catalog.length} categories, ` +
    `${catalog.reduce((n, c) => n + c.courses.length, 0)} courses`
);
